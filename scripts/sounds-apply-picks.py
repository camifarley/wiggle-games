# Wires a Sound Picker export (sound-picks-*.json) into the games: copies the chosen candidates to
# public/sounds/sfx/, evens out their loudness, and writes src/core/sound-picks.js.
#
# Usage: venv/bin/python -I sounds-apply-picks.py <sound-picks.json> <repo_dir>
#   Needs soundfile + numpy and macOS afconvert. Music rows (music:*) are not touched (see music-picks.js).
#
# Rules (agreed with the parent):
# - Sounds that repeat a lot ROTATE through every 👍 (⭐ favorite plays 3x as often; never the same twice in a row).
# - "Moment" sounds use ONE sound (the ⭐, else the first 👍), so the sound becomes the sound of that moment.
# - Loudness is matched per slot (TARGET_DB), then the parent's per-sound louder/quieter votes are applied.
import json, os, subprocess, sys, tempfile
import numpy as np
import soundfile as sf

EXPORT, REPO = sys.argv[1], sys.argv[2]
ROTATE = {'pop', 'boing', 'smash', 'boom', 'bonk', 'laser', 'sonic', 'step', 'cubes', 'splat', 'punch', 'squeak', 'giggle', 'whoosh'}
# classic sfx names a slot takes over (sfx.ding() -> collect). Slots named like a classic sfx take it over anyway.
REPLACES = {'collect': ['ding'], 'powerup': ['tada']}
# loudness of the "active" part of each sound, dBFS RMS. Taps and footsteps sit lower; booms a bit higher.
TARGET_DB = {'tap': -24, 'step': -21, 'engine': -22, 'shield': -21, 'cubes': -19, 'boom': -14, 'smash': -15}
DEFAULT_DB = -17
PEAK = 10 ** (-1 / 20)
STEP_DB = 4  # one 🔊 louder / 🔉 quieter vote in the Picker

OUT = os.path.join(REPO, 'public', 'sounds', 'sfx')
picks = json.load(open(EXPORT))
cands = {}
for path in ('candidates.json', 'candidates-extra.json'):
    full = os.path.join(REPO, 'public', 'sounds', path)
    if not os.path.exists(full): continue
    d = json.load(open(full))
    slots = d['slots'] if isinstance(d['slots'], list) else [{'slot': k, 'candidates': v} for k, v in d['slots'].items()]
    for s in slots:
        for c in s['candidates']: cands[(s['slot'], c['id'])] = c

def load(path):
    tmp = tempfile.mktemp(suffix='.wav')
    subprocess.run(['afconvert', '-f', 'WAVE', '-d', 'LEI16', path, tmp], check=True)
    d, sr = sf.read(tmp, always_2d=True); os.remove(tmp)
    return d.mean(axis=1).astype(np.float64), sr

def level(x, db, extra_db):
    peak = np.abs(x).max() + 1e-12
    active = x[np.abs(x) > peak * 10 ** (-40 / 20)]
    rms = np.sqrt((active ** 2).mean()) + 1e-12
    y = x * (10 ** ((db + extra_db) / 20) / rms)
    if np.abs(y).max() > PEAK: y *= PEAK / np.abs(y).max()  # never clip; the limiter in audio.js does the rest
    return y

def encode(x, sr, out):
    tmp = tempfile.mktemp(suffix='.wav')
    sf.write(tmp, x, sr, subtype='PCM_16')
    subprocess.run(['afconvert', '-f', 'm4af', '-d', 'aac', '-b', '96000', tmp, out], check=True)
    os.remove(tmp)

os.makedirs(OUT, exist_ok=True)
for f in os.listdir(OUT):
    if f.endswith('.m4a'): os.remove(os.path.join(OUT, f))
lines, report = [], []
for slot, p in picks['slots'].items():
    if slot.startswith('music:'): continue
    fav, ups = p.get('favorite'), [u for u in p.get('up', []) if u not in p.get('down', [])]
    order = ([fav] if fav else []) + [u for u in ups if u != fav]
    if not order: continue
    if slot not in ROTATE: order = order[:1]
    gain_votes = p.get('gain', {})  # {id: +1 louder | -1 quieter} from the Picker (round 3+)
    files, weights, names = [], [], []
    for i, cid in enumerate(order):
        c = cands.get((slot, cid))
        if not c or 'file' not in c:
            print('skip (not a file):', slot, cid); continue
        x, sr = load(os.path.join(REPO, 'public', c['file']))
        y = level(x, TARGET_DB.get(slot, DEFAULT_DB), STEP_DB * gain_votes.get(cid, 0))
        name = f'{slot}-{len(files) + 1}.m4a'
        encode(y, sr, os.path.join(OUT, name))
        files.append(f'sounds/sfx/{name}')
        weights.append(3 if cid == fav and len(order) > 1 else 1)
        names.append(cid + (' ⭐' if cid == fav else ''))
    if not files: continue
    entry = {'files': files}
    if any(w != 1 for w in weights): entry['weights'] = weights
    if slot in REPLACES: entry['replaces'] = REPLACES[slot]
    lines.append(f"  {slot}: {json.dumps(entry)}, // {', '.join(names)}")
    report.append((slot, len(files)))

js = open(os.path.join(REPO, 'src', 'core', 'sound-picks.js')).read()
head = ''.join(l for l in js[: js.index('export const PICKS')].splitlines(True) if not l.startswith('// Generated by'))
src = os.path.basename(EXPORT)
body = f"// Generated by scripts/sounds-apply-picks.py from {src}. Re-run it after a new export.\nexport const PICKS = {{\n" + '\n'.join(lines) + '\n};\n'
open(os.path.join(REPO, 'src', 'core', 'sound-picks.js'), 'w').write(head + body)
total = sum(os.path.getsize(os.path.join(OUT, f)) for f in os.listdir(OUT))
print(report, f'{total / 1024:.0f} KB')
